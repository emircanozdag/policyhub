CREATE TABLE quote (
    id                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_number        VARCHAR2(32)    NOT NULL,
    product_type        VARCHAR2(20)    NOT NULL,
    plate_number        VARCHAR2(16)    NOT NULL,
    vehicle_model_year  NUMBER(4)       NOT NULL,
    vehicle_value       NUMBER(15, 2)   NOT NULL,
    driver_age          NUMBER(3)       NOT NULL,
    claim_count         NUMBER(3)       NOT NULL,
    premium             NUMBER(15, 2)   NOT NULL,
    status              VARCHAR2(20)    NOT NULL,
    valid_until         DATE            NOT NULL,
    created_at          TIMESTAMP       NOT NULL,
    CONSTRAINT uk_quote_number UNIQUE (quote_number),
    CONSTRAINT ck_quote_status CHECK (status IN ('ACTIVE', 'CONVERTED', 'EXPIRED'))
);

CREATE TABLE policy (
    id                  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_number       VARCHAR2(32)    NOT NULL,
    quote_id            NUMBER(19)      NOT NULL,
    product_type        VARCHAR2(20)    NOT NULL,
    plate_number        VARCHAR2(16)    NOT NULL,
    premium             NUMBER(15, 2)   NOT NULL,
    start_date          DATE            NOT NULL,
    end_date            DATE            NOT NULL,
    status              VARCHAR2(20)    NOT NULL,
    created_at          TIMESTAMP       NOT NULL,
    CONSTRAINT uk_policy_number UNIQUE (policy_number),
    CONSTRAINT fk_policy_quote FOREIGN KEY (quote_id) REFERENCES quote (id),
    CONSTRAINT ck_policy_status CHECK (status IN ('ACTIVE', 'CANCELLED', 'EXPIRED'))
);

-- Used by the nightly renewal batch job (phase 2)
CREATE INDEX ix_policy_status_end_date ON policy (status, end_date);
